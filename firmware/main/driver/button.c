int
btn_init(const btn_config_t *config, btn_t *btn)
{
    if (gpio_set_direction(config->gpio, GPIO_MODE_INPUT) != ESP_OK)
    {
        return RET_ERR_FAIL;
    }
    if (gpio_pullup_en(config->gpio) != ESP_OK)
    {
        return RET_ERR_FAIL;
    }

    btn->cfg = *config;

    return RET_OK;
}

bool
btn_is_pressed(btn_t *btn)
{ return btn->cfg.active_high == gpio_get_level(btn->cfg.gpio); }

